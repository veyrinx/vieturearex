/**
 * Danh mục mọi mục quản trị mở được trong app.
 *
 * Một chỗ duy nhất: App.tsx dựng route từ đây, màn Quản trị dựng danh sách từ
 * đây. Thêm mục mới = thêm một dòng, không phải sửa hai file.
 *
 * `component` để trống nghĩa là mục đó dùng màn hình sẵn có ở `path` khác (ví dụ
 * Nội dung nằm ngay trên thanh tab) — chỉ hiện trong danh sách để tìm cho nhanh.
 */

export type AdminEntry = AdminSection & { component?: ComponentType };

const lazyScreen = <T extends string>(load: () => Promise<Record<T, ComponentType>>, name: T) =>
  lazy(() => load().then((module) => ({ default: module[name] })));

/** Bọc một khai báo tài nguyên thành màn hình dùng chung. */
function resourceScreen(config: ResourceConfig, title: string, description?: string) {
  return lazy(async () => {
    const module = await import("@/components/resource-screen");
    const Screen = (
      config.kind === "array" ? module.ArrayResourceScreen : module.RowResourceScreen
    ) as ComponentType<{ config: ResourceConfig; title: string; description?: string }>;
    return {
      default: () => <Screen config={config} title={title} description={description} />,
    };
  });
}

